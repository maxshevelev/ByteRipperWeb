#!/usr/bin/env python3
"""Bring the compiled map files across from ByteRipper, or check they are level.

Upstream keeps six families of descriptions — strap tables, descriptor
registers, ME configuration, UEP, GPIO and CSME 18 layouts — as JSON and
compiles each into a BRM1 binary with a version mark the reading code carries
too (upstream's Design/MAP_DATA.md). The JSON stays upstream; the web takes the
binaries byte for byte and marks its readers with the same versions.

This copies each binary into src/firmware/mapData/data/ and writes the six
marks, read from upstream's generated *DataVersion.swift files, into
src/firmware/mapData/mapDataVersions.ts. With --check it writes nothing and
fails when either differs from upstream's, so a stale pair is reported rather
than shipped.

Standard library only, by the repository's skill rules.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

SKILL_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = SKILL_DIR.parent.parent
DATA_DIR = REPO_ROOT / "src" / "firmware" / "mapData" / "data"
VERSIONS_PATH = REPO_ROOT / "src" / "firmware" / "mapData" / "mapDataVersions.ts"

# family → (upstream binary, upstream version mark, the mark's Swift type)
FAMILIES = {
    "strap": (
        "Packages/UEFIImage/Sources/UEFIImage/Resources/StrapMaps/StrapMaps.bin",
        "Packages/UEFIImage/Sources/UEFIImage/StrapMapDataVersion.swift",
        "StrapMapDataVersion",
    ),
    "register": (
        "Packages/UEFIImage/Sources/UEFIImage/Resources/RegisterMaps/RegisterMaps.bin",
        "Packages/UEFIImage/Sources/UEFIImage/DescriptorRegisterMapDataVersion.swift",
        "DescriptorRegisterMapDataVersion",
    ),
    "configuration": (
        "Packages/MEFirmware/Sources/MEFirmware/Resources/ConfigMaps/ConfigMaps.bin",
        "Packages/MEFirmware/Sources/MEFirmware/Configuration/MEConfigurationDataVersion.swift",
        "MEConfigurationDataVersion",
    ),
    "uep": (
        "Packages/MEFirmware/Sources/MEFirmware/Resources/UEPMaps/UEPMaps.bin",
        "Packages/MEFirmware/Sources/MEFirmware/Configuration/UEPMapDataVersion.swift",
        "UEPMapDataVersion",
    ),
    "gpio": (
        "Packages/MEFirmware/Sources/MEFirmware/Resources/GPIOMaps/GPIOMaps.bin",
        "Packages/MEFirmware/Sources/MEFirmware/Configuration/GPIOPinMapDataVersion.swift",
        "GPIOPinMapDataVersion",
    ),
    "layout": (
        "Packages/MEFirmware/Sources/MEFirmware/Resources/LayoutMaps/LayoutMaps.bin",
        "Packages/MEFirmware/Sources/MEFirmware/Configuration/LayoutMapDataVersion.swift",
        "LayoutMapDataVersion",
    ),
}


def fail(message: str) -> "NoReturn":  # type: ignore[name-defined]
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def find_source_repo(explicit: str | None) -> Path:
    """Locate the ByteRipper clone: --repo, $BYTERIPPER_REPO, then ../ByteRipper."""
    candidates = []
    if explicit:
        candidates.append(Path(explicit).expanduser())
    if os.environ.get("BYTERIPPER_REPO"):
        candidates.append(Path(os.environ["BYTERIPPER_REPO"]).expanduser())
    candidates.append(REPO_ROOT.parent / "ByteRipper")
    for path in candidates:
        if (path / ".git").exists():
            return path.resolve()
    tried = "\n  ".join(str(c) for c in candidates)
    fail(f"no ByteRipper clone found. Tried:\n  {tried}")


def read_mark(path: Path) -> tuple[int, int]:
    """The format version and the data version a generated Swift mark states."""
    text = path.read_text(encoding="utf-8")
    fmt = re.search(r"formatVersion:\s*UInt16\s*=\s*(\d+)", text)
    version = re.search(r"\bversion:\s*UInt32\s*=\s*(\d+)", text)
    if not fmt or not version:
        fail(f"{path} does not state formatVersion and version")
    return int(fmt.group(1)), int(version.group(1))


def versions_module(marks: dict[str, tuple[int, int]]) -> str:
    lines = [
        "// Generated by `Skills/port-from-byteripper/scripts/sync_maps.py`. Do not edit.",
        "//",
        "// The version each family's binary was compiled with upstream, which the",
        "// reader compares with the file's own before reading a section: a stale",
        "// resource is reported before a byte of it is interpreted.",
        "",
        "export const MAP_DATA_VERSIONS = {",
    ]
    for family, (_, mark, name) in FAMILIES.items():
        fmt, version = marks[family]
        lines.append(f"  /**")
        lines.append(f"   * @upstream {mark}#{name}")
        lines.append(f"   * @upstream {mark}#{name}.formatVersion")
        lines.append(f"   * @upstream {mark}#{name}.version")
        lines.append(f"   */")
        lines.append(f"  {family}: {{ formatVersion: {fmt}, version: {version} }},")
    lines.append("} as const;")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--repo", help="the ByteRipper clone")
    parser.add_argument(
        "--check", action="store_true", help="write nothing; fail when the web's pair differs"
    )
    args = parser.parse_args()
    source = find_source_repo(args.repo)

    marks: dict[str, tuple[int, int]] = {}
    stale: list[str] = []
    for family, (binary, mark, _) in FAMILIES.items():
        upstream_bin = source / binary
        if not upstream_bin.exists():
            fail(f"{upstream_bin} is missing")
        marks[family] = read_mark(source / mark)
        target = DATA_DIR / upstream_bin.name
        wanted = upstream_bin.read_bytes()
        if not target.exists() or target.read_bytes() != wanted:
            stale.append(str(target.relative_to(REPO_ROOT)))
            if not args.check:
                DATA_DIR.mkdir(parents=True, exist_ok=True)
                target.write_bytes(wanted)

    module = versions_module(marks)
    if not VERSIONS_PATH.exists() or VERSIONS_PATH.read_text(encoding="utf-8") != module:
        stale.append(str(VERSIONS_PATH.relative_to(REPO_ROOT)))
        if not args.check:
            VERSIONS_PATH.write_text(module, encoding="utf-8")

    if args.check:
        if stale:
            print("not level with upstream:", *stale, sep="\n  ")
            raise SystemExit(1)
        print("the map data is level with upstream")
    else:
        print("brought across:" if stale else "already level", *stale, sep="\n  ")


if __name__ == "__main__":
    main()
