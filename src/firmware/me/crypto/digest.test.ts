import { describe, expect, it } from "vitest";
import { hex, sameBytes, sha1, sha256, sha384 } from "@/firmware/me/crypto/digest";

/**
 * The three digests against the vectors FIPS 180-4 and NIST's CAVP publish.
 *
 * These are hand-written rather than taken from a package, so this file is the
 * whole of the argument that they are right — which is why it covers the empty
 * message, the one-block case, the case that straddles a block boundary, and a
 * long message that forces many blocks.
 */

const ascii = (text: string) => Uint8Array.from(text, (one) => one.charCodeAt(0));
const repeated = (text: string, times: number) => ascii(text.repeat(times));

describe("sha1", () => {
  it("matches the published vectors", () => {
    expect(hex(sha1(new Uint8Array(0)))).toBe("DA39A3EE5E6B4B0D3255BFEF95601890AFD80709");
    expect(hex(sha1(ascii("abc")))).toBe("A9993E364706816ABA3E25717850C26C9CD0D89D");
    // 56 bytes: the case that needs a second block for the length alone.
    expect(hex(sha1(ascii("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")))).toBe(
      "84983E441C3BD26EBAAE4AA1F95129E5E54670F1"
    );
    // A million 'a': many blocks, and the one that catches a bad length field.
    expect(hex(sha1(repeated("a", 1_000_000)))).toBe("34AA973CD4C4DAA4F61EEB2BDBAD27316534016F");
  });
});

describe("sha256", () => {
  it("matches the published vectors", () => {
    expect(hex(sha256(new Uint8Array(0)))).toBe(
      "E3B0C44298FC1C149AFBF4C8996FB92427AE41E4649B934CA495991B7852B855"
    );
    expect(hex(sha256(ascii("abc")))).toBe(
      "BA7816BF8F01CFEA414140DE5DAE2223B00361A396177A9CB410FF61F20015AD"
    );
    expect(hex(sha256(ascii("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")))).toBe(
      "248D6A61D20638B8E5C026930C3E6039A33CE45964FF2167F6ECEDD419DB06C1"
    );
    expect(hex(sha256(repeated("a", 1_000_000)))).toBe(
      "CDC76E5C9914FB9281A1C7E284D73E67F1809A48A497200E046D39CCC7112CD0"
    );
  });

  it("is right either side of a block boundary", () => {
    // 55 bytes fit with the length; 56 do not and force another block. A padding
    // bug shows here and nowhere else.
    expect(hex(sha256(repeated("a", 55)))).toBe(
      "9F4390F8D30C2DD92EC9F095B65E2B9AE9B0A925A5258E241C9F1E910F734318"
    );
    expect(hex(sha256(repeated("a", 56)))).toBe(
      "B35439A4AC6F0948B6D6F9E3C6AF0F5F590CE20F1BDE7090EF7970686EC6738A"
    );
    expect(hex(sha256(repeated("a", 64)))).toBe(
      "FFE054FE7AE0CB6DC65C3AF9B61D5209F439851DB43D0BA5997337DF154668EB"
    );
  });
});

describe("sha384", () => {
  it("matches the published vectors", () => {
    expect(hex(sha384(new Uint8Array(0)))).toBe(
      "38B060A751AC96384CD9327EB1B1E36A21FDB71114BE07434C0CC7BF63F6E1DA274EDEBFE76F65FBD51AD2F14898B95B"
    );
    expect(hex(sha384(ascii("abc")))).toBe(
      "CB00753F45A35E8BB5A03D699AC65007272C32AB0EDED1631A8B605A43FF5BED8086072BA1E7CC2358BAECA134C825A7"
    );
    // 112 bytes: the 1024-bit block's own straddling case.
    expect(
      hex(
        sha384(
          ascii(
            "abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmn" +
              "hijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu"
          )
        )
      )
    ).toBe(
      "09330C33F71147E83D192FC782CD1B4753111B173B3B05D22FA08086E3B0F712FCC7C71A557E2DB966C3E9FA91746039"
    );
    expect(hex(sha384(repeated("a", 1_000_000)))).toBe(
      "9D0E1809716474CB086E834E310A4A1CED149E9C00F248527972CEC5704C2A5B07B8B3DC38ECC4EBAE97DDD87F3D8985"
    );
  });

  it("is right either side of a block boundary", () => {
    // The 64-bit family pads to 128 bytes with a 128-bit length, so 111 fits
    // and 112 does not.
    expect(hex(sha384(repeated("a", 111)))).toBe(
      "3C37955051CB5C3026F94D551D5B5E2AC38D572AE4E07172085FED81F8466B8F90DC23A8FFCDEA0B8D8E58E8FDACC80A"
    );
    expect(hex(sha384(repeated("a", 112)))).toBe(
      "187D4E07CB306103C69967BF544D0DFBE9042577599C73C330ABC0CB64C61236D5ED565EE19119D8C31779A38F791FCD"
    );
  });
});

