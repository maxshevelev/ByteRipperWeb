/** The bytes the table above is of. */
const pattern = (length: number) =>
  Uint8Array.from({ length }, (_, index) => (index * 131 + 7) & 0xff);

describe("against a reference implementation", () => {
  // The published vectors pin down four lengths each. This pins down every
  // length where a padding or a length-field mistake actually lives, which is
  // the whole of the argument for writing these by hand rather than taking a
  // package.
  it("agrees at every length around a block boundary", () => {
    for (const [length, one, two, three] of REFERENCE) {
      const bytes = pattern(length);
      expect(hex(sha1(bytes)), `sha1 of ${length} bytes`).toBe(one);
      expect(hex(sha256(bytes)), `sha256 of ${length} bytes`).toBe(two);
      expect(hex(sha384(bytes)), `sha384 of ${length} bytes`).toBe(three);
    }
  });
});

describe("hex and sameBytes", () => {
  it("spells a digest the way upstream shows it", () => {
    expect(hex(Uint8Array.of(0x00, 0x0a, 0xff))).toBe("000AFF");
  });

  it("compares by bytes and not by length alone", () => {
    expect(sameBytes(Uint8Array.of(1, 2), Uint8Array.of(1, 2))).toBe(true);
    expect(sameBytes(Uint8Array.of(1, 2), Uint8Array.of(1, 3))).toBe(false);
    expect(sameBytes(Uint8Array.of(1, 2), Uint8Array.of(1, 2, 3))).toBe(false);
  });
});
