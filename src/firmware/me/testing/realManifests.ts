/**
 * Real manifest vectors for signature validation.
 *
 * Three manifests taken from oracle whole-flash images: CSME 12 is 2048-bit
 * PKCS #1 v1.5 over SHA-256, CSME 15 and 16 are 3072-bit SSA-PSS over SHA-384.
 * Their validity was confirmed against a line-for-line mirror of upstream's own
 * `rsa_sig_val`, so a port that agrees with these agrees with upstream.
 *
 * These are not a firmware dump and nothing here is flashable: a public key, a
 * signature, and the manifest's own protected window — a few kilobytes of
 * Intel's published signing material, which is upstream's committed fixture
 * too. The rule against committing a dump stands; this is the material a
 * signature check needs and nothing else.
 *
 * CSME 16 earns its place: its modulus's top limb is at or above 0x80000000,
 * the geometry that broke upstream's own Montgomery reduction. This port does
 * the arithmetic with the language's own `bigint`, where that class of mistake
 * cannot arise — so the vector stays as the guard it was, now against a
 * different implementation.
 */

/**
 * Even-length uppercase hex, as bytes.
 *
 * @upstream Packages/MEFirmware/Tests/MEFirmwareTests/RealManifests.swift#RealManifests
 * @upstream Packages/MEFirmware/Tests/MEFirmwareTests/RealManifests.swift#RealManifests.hex
 */
export function fromHex(text: string): Uint8Array {
  const bytes = new Uint8Array(text.length / 2);
  for (let index = 0; index < bytes.length; index++) {
    bytes[index] = Number.parseInt(text.slice(index * 2, index * 2 + 2), 16);
  }
  return bytes;
}

