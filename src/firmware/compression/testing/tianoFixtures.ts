/**
 * Tiano and EFI 1.1 streams for the decoder's tests, in the layout EDK2 writes:
 * the compressed size and the original size, each 32 bits, then the stream.
 * Generated once with EDK2's own compressor — the `EfiTianoCompress.c` upstream
 * vendors under `Sources/CTianoEncoder` — so no encoder is part of this project
 * and no test reaches for one.
 *
 * The input is upstream's own: `tianoSample()` below is `TianoTests.sample()`,
 * at 8,000 bytes rather than its 40,000. The stream is checked in here instead
 * of being encoded in the test, and five times the bytes would be five times the
 * fixture for the same decoder paths.
 */

/** Upstream's sample: a pattern that repeats often enough to compress. */
export function tianoSample(count = 8000): Uint8Array {
  return Uint8Array.from(
    { length: count },
    (_, index) => (((index * 7) % 251) ^ (index >> 9)) & 0xff
  );
}

