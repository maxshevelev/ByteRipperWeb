/**
 * LZMA streams for the decoder's tests, in the layout EDK2 writes: five
 * property bytes (lc 3, lp 0, pb 2, a 64 KiB dictionary), the uncompressed
 * size as 64 bits, then the stream. Generated once with Python's `lzma`
 * (FORMAT_RAW, FILTER_LZMA1, and FILTER_X86 before it for the filtered one),
 * so no encoder is part of this project and no test reaches for one.
 *
 * The inputs are upstream's own: `sample()` below is `LZMATests.sample()`, and
 * the module bodies are `LZMAModuleTests`'s.
 */

/** Upstream's sample: runs of a pattern, with x86 `call rel32` instructions through them. */
export function lzmaSample(count = 70_000): Uint8Array {
  const bytes: number[] = [];
  while (bytes.length < count) {
    bytes.push(0xe8, 0x10, 0x00, 0x00, 0x00);
    const at = bytes.length;
    for (let index = 0; index < 27; index++) bytes.push((index * 7 + Math.floor(at / 64)) & 0xff);
  }
  return Uint8Array.from(bytes.slice(0, count));
}

/** `LZMAModuleTests`'s body. */
export const lzmaModuleBody = (): Uint8Array =>
  Uint8Array.from({ length: 3000 }, (_, index) => Math.floor((index * 31) / 7) & 0xff);

export function fixtureBytes(lines: readonly string[]): Uint8Array {
  const text = lines.join("");
  const bytes = new Uint8Array(text.length / 2);
  for (let index = 0; index < bytes.length; index++) {
    bytes[index] = Number.parseInt(text.slice(index * 2, index * 2 + 2), 16);
  }
  return bytes;
}

